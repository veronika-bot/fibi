// ── Вспомогательные функции ──────────────────────────────────
function getTaskById(id) {
  return TASK_BANK.find(t => t.id === id);
}

function getTasksByTopic(topicId) {
  const topic = TOPICS.find(t => t.id === topicId);
  if (!topic) return [];
  return topic.tasks.map(id => getTaskById(id)).filter(Boolean);
}

function getTasksByDifficulty(level) {
  return TASK_BANK.filter(t => t.difficulty === level);
}

function checkAnswer(task, userAnswer) {
  const ua = userAnswer.trim().toLowerCase().replace(/\s+/g, '');
  const correct = task.answer.toLowerCase().replace(/\s+/g, '');
  if (ua === correct) return true;
  return task.answerAlt.some(a => ua === a.toLowerCase().replace(/\s+/g, ''));
}

function getRandomTasks(n = 5, topicId = null) {
  let pool = topicId ? getTasksByTopic(topicId) : [...TASK_BANK];
  pool = pool.sort(() => Math.random() - 0.5);
  return pool.slice(0, n);
}

